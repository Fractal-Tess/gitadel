import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// This glue connects existing URL-based callers to Hey API's operation types.
// It contains no independent request or response definitions.
const spec = JSON.parse(await readFile(new URL('../../api/openapi.json', import.meta.url), 'utf8'));
const operations: string[] = [];
const names: string[] = [];
for (const [path, item] of Object.entries(spec.paths) as [string, Record<string, { operationId: string; responses: Record<string, unknown> }> ][]) {
  for (const [method, operation] of Object.entries(item)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
    const name = operation.operationId.split('_').filter(Boolean).map((s: string) => s[0].toUpperCase() + s.slice(1)).join('');
    const success = Object.keys(operation.responses).some(status => status.startsWith('2'));
    names.push(`${name}Data`);
    if (success) names.push(`${name}Responses`);
    operations.push(`  ${JSON.stringify(operation.operationId)}: { method: ${JSON.stringify(method.toUpperCase())}; data: ${name}Data; response: ${success ? `${name}Responses[keyof ${name}Responses]` : 'void'} };`);
  }
}
const text = `// Generated by scripts/api-contracts.ts from the registered Rust API. Do not edit.\nimport type {\n  ${names.join(',\n  ')}\n} from './generated/types.gen.js';\n\nexport interface Operations {\n${operations.join('\n')}\n}\n`;
await mkdir(new URL('../src/lib/api', import.meta.url), { recursive: true });
await writeFile(process.env.GITADEL_CONTRACTS_OUTPUT ?? new URL('../src/lib/api/contracts.gen.ts', import.meta.url), text);
await copyFile(new URL('../node_modules/@hey-api/openapi-ts/LICENSE.md', import.meta.url),
  resolve(process.env.GITADEL_SDK_OUTPUT ?? new URL('../src/lib/api/generated', import.meta.url).pathname, 'LICENSE.md'));
